inline const Glyph* find(char c) {
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    int n; const Glyph* t = table(n); for (int i = 0; i < n; i++) if (t[i].c == c) return &t[i];
    return nullptr;                                         // desconocido: se dibuja como '?'
}
