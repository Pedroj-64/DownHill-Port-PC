constexpr int kGlyphW = 5, kGlyphH = 7, kGlyphAdvance = 6;
inline float textWidth(const std::string& s, float scale) { return s.empty() ? 0.f : (s.size() * kGlyphAdvance - 1) * scale; }
// Rectángulos de `s` con la esquina superior izquierda en (x, y); `scale` = píxeles de pantalla por píxel de fuente.
inline void textQuads(const std::string& s, float x, float y, float scale, float r, float g, float b, float a, std::vector<Quad>& out) {
    float cx = x;
    for (char ch : s) {
        const font5x7::Glyph* gl = font5x7::find(ch); if (!gl) gl = font5x7::find('?');
        for (int row = 0; row < kGlyphH; row++) {              // une los píxeles contiguos de cada fila en un solo rectángulo
            for (int col = 0; col < kGlyphW;) {
                if (gl->rows[row][col] != '#') { col++; continue; }
                int e = col; while (e < kGlyphW && gl->rows[row][e] == '#') e++;
                out.push_back({cx + col * scale, y + row * scale, (e - col) * scale, scale, r, g, b, a}); col = e;
            }
        }
        cx += kGlyphAdvance * scale;
    }
}
inline void textQuadsCentered(const std::string& s, float cx, float y, float scale, float r, float g, float b, float a, std::vector<Quad>& out) { textQuads(s, cx - textWidth(s, scale) * 0.5f, y, scale, r, g, b, a, out); }
